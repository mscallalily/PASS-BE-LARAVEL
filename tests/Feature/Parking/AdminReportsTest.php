<?php

namespace Tests\Feature\Parking;

use App\Services\Reports\ReportFilters;
use App\Support\CampusTime;
use Carbon\CarbonImmutable;
use Illuminate\Support\Facades\DB;
use Laravel\Sanctum\Sanctum;

class AdminReportsTest extends ParkingTestCase
{
    private function report(string $category, array $filters = [])
    {
        return $this->getJson('/api/admin/reports?'.http_build_query($filters + ['category' => $category, 'date_from' => CampusTime::date(), 'date_to' => CampusTime::date()]));
    }

    public function test_only_active_admins_can_view_or_export_reports(): void
    {
        foreach (['student', 'faculty', 'employee', 'security', 'other'] as $type) {
            Sanctum::actingAs($this->user($type));
            $this->getJson('/api/admin/reports')->assertForbidden();
            $this->getJson('/api/admin/reports/export?format=csv')->assertForbidden();
        }
    }

    public function test_every_category_and_rfid_dataset_resolves_with_real_rows_and_safe_fields(): void
    {
        $this->actingAsStaff();
        $car = $this->campusVehicle();
        $this->gate('entry', ['rfid_tag_uid' => $car['tag']]);
        $visitor = $this->visitorVehicle();
        DB::table('visitor_requests')->insert(['visitor_id' => $visitor['visitor_id'], 'vehicle_id' => $visitor['vehicle_id'], 'purpose' => 'QA visit', 'requested_valid_from' => now(), 'requested_valid_until' => now()->addHours(2), 'created_at' => now(), 'updated_at' => now()]);
        DB::table('audit_logs')->insert(['actor_label' => 'QA', 'action' => 'report_qa', 'new_values' => json_encode(['status' => 'approved', 'password' => 'PRIVATE', 'nested' => ['token' => 'SECRET']]), 'created_at' => now()]);
        $this->actingAsAdmin();
        foreach (array_keys(ReportFilters::TITLES) as $category) {
            $r = $this->report($category)->assertOk()->assertJsonStructure(['data', 'summary', 'charts', 'meta' => ['columns', 'date_basis', 'total_records'], 'pagination', 'snapshot' => ['overall', 'inside']]);
            $this->assertStringNotContainsString('PRIVATE', $r->getContent());
            $this->assertStringNotContainsString('SECRET', $r->getContent());
            if ($category !== 'security') {
                $this->assertGreaterThan(0, $r->json('pagination.total'), $category);
            }
        }
        foreach (['assignments', 'devices'] as $dataset) {
            $this->report('rfid', ['dataset' => $dataset])->assertOk();
        }
    }

    public function test_pagination_summary_and_exports_use_all_matching_rows_not_just_the_page(): void
    {
        $this->actingAsAdmin();
        $rows = [];
        for ($i = 0; $i < 515; $i++) {
            $rows[] = ['actor_label' => 'QA', 'action' => 'report_paging', 'new_values' => json_encode(['status' => 'approved']), 'created_at' => now()];
        }
        DB::table('audit_logs')->insert($rows);
        $r = $this->report('audit', ['search' => 'report_paging', 'per_page' => 10, 'page' => 2])->assertOk();
        $this->assertCount(10, $r->json('data'));
        $this->assertSame(515, $r->json('pagination.total'));
        $this->assertSame(515, $r->json('summary.0.value'));
        $query = http_build_query(['category' => 'audit', 'search' => 'report_paging', 'per_page' => 10, 'page' => 2]);
        $csv = $this->get('/api/admin/reports/export?'.$query.'&format=csv')->assertOk()->streamedContent();
        $csvRows = array_map('str_getcsv', explode("\n", $csv));
        $this->assertCount(515, array_filter($csvRows, fn ($line) => count($line) > 6 && ($line[6] ?? null) === 'report_paging'));
        $this->assertStringContainsString('Generated by', $csv);
        $xml = $this->get('/api/admin/reports/export?'.$query.'&format=excel')->assertOk()->streamedContent();
        $this->assertStringContainsString('urn:schemas-microsoft-com:office:spreadsheet', $xml);
        $document = new \DOMDocument;
        $this->assertTrue($document->loadXML($xml, LIBXML_NONET));
        $html = $this->get('/api/admin/reports/export?'.$query.'&format=print')->assertOk()->streamedContent();
        $this->assertStringContainsString('Save as PDF', $html);
    }

    public function test_entry_counts_duration_and_manila_boundaries_match_admin_dashboard(): void
    {
        $this->travelTo(CarbonImmutable::parse('2026-11-20 23:30', 'Asia/Manila'));
        $this->actingAsStaff();
        $car = $this->campusVehicle();
        $this->gate('entry', ['rfid_tag_uid' => $car['tag']]);
        $this->travelTo(CarbonImmutable::parse('2026-11-21 00:30', 'Asia/Manila'));
        $this->gate('exit', ['rfid_tag_uid' => $car['tag']]);
        $this->gate('entry', ['rfid_tag_uid' => 'UNKNOWN-REPORT-QA']);
        $this->actingAsAdmin();
        $r = $this->report('entry-exit')->assertOk();
        $metrics = collect($r->json('summary'))->pluck('value', 'label');
        $this->assertEquals(0, $metrics['Entries in period']);
        $this->assertEquals(1, $metrics['Exits in period']);
        $this->assertEquals(60, $metrics['Average completed stay']);
        $this->assertEquals(60, $r->json('data.0.duration_minutes'));
        $this->getJson('/api/admin/dashboard')->assertOk()->assertJsonPath('today_activity.entries', 0)->assertJsonPath('today_activity.exits', 1);
        $this->assertSame(1, $r->json('snapshot.today_denied'));
        $this->assertSame(0, array_sum(array_column($r->json('charts.daily'), 'records')));
        DB::table('audit_logs')->insert(['actor_label' => 'QA', 'action' => 'midnight_qa', 'created_at' => CampusTime::stored(CarbonImmutable::parse('2026-11-21 00:15', 'Asia/Manila'))]);
        $this->getJson('/api/admin/audit-logs?search=midnight_qa&date_from=2026-11-21&date_to=2026-11-21')->assertOk()->assertJsonPath('total', 1);
        $this->report('rfid', ['status' => 'denied'])->assertOk()->assertJsonPath('pagination.total', 1)->assertJsonPath('data.0.vehicle_type', null);
    }

    public function test_reconstructed_occupancy_counts_carry_in_and_clips_at_exit(): void
    {
        $this->travelTo(CarbonImmutable::parse('2026-11-20 23:30', 'Asia/Manila'));
        $this->actingAsStaff();
        $car = $this->campusVehicle();
        $this->gate('entry', ['rfid_tag_uid' => $car['tag']]);
        $this->travelTo(CarbonImmutable::parse('2026-11-21 00:30', 'Asia/Manila'));
        $this->gate('exit', ['rfid_tag_uid' => $car['tag']]);
        $this->travelTo(CarbonImmutable::parse('2026-11-21 01:00', 'Asia/Manila'));
        $this->actingAsAdmin();
        $r = $this->report('occupancy', ['vehicle_type' => 'car'])->assertOk();
        $this->assertCount(1, $r->json('data'));
        $this->assertEquals(1, $r->json('data.0.peak_vehicles'));
        $this->assertEquals(0.5, $r->json('data.0.average_vehicles'));
        $this->assertEquals(0.5, collect($r->json('summary'))->firstWhere('label', 'Recorded vehicle-hours')['value']);
        $this->assertSame(0, $r->json('snapshot.inside.total'));
    }

    public function test_filters_are_applied_before_counts_and_do_not_truncate_older_rows(): void
    {
        $this->actingAsStaff();
        $car = $this->campusVehicle();
        $bike = $this->campusVehicle('motorcycle');
        $this->gate('entry', ['rfid_tag_uid' => $car['tag']]);
        $this->gate('entry', ['rfid_tag_uid' => $bike['tag']]);
        $this->actingAsAdmin();
        $this->report('entry-exit', ['vehicle_type' => 'motorcycle'])->assertOk()->assertJsonPath('pagination.total', 1)->assertJsonPath('data.0.plate_number', $bike['plate']);
        $this->report('vehicles', ['search' => $car['plate']])->assertOk()->assertJsonPath('pagination.total', 1)->assertJsonPath('data.0.plate_number', $car['plate']);
        $this->report('users', ['vehicle_type' => 'car'])->assertUnprocessable();
        $this->report('entry-exit', ['status' => 'bogus'])->assertUnprocessable();
        $this->report('entry-exit', ['date_from' => '2020-01-01', 'date_to' => '2026-01-01'])->assertUnprocessable();
    }

    public function test_security_includes_denials_overrides_and_structural_conflicts(): void
    {
        $this->actingAsStaff();
        $car = $this->campusVehicle();
        $this->gate('entry', ['plate_number' => $car['plate']]);
        $this->gate('entry', ['rfid_tag_uid' => 'UNKNOWN-REPORT-QA']);
        $transaction = $this->activeTransaction($car['vehicle_id']);
        DB::table('parking_transactions')->where('transaction_id', $transaction->transaction_id)->update(['slot_id' => null]);
        $this->actingAsAdmin();
        foreach (['denied', 'manual_override', 'integrity_warning'] as $status) {
            $this->report('security', ['status' => $status])->assertOk()->assertJsonPath('pagination.total', 1);
        }
    }

    public function test_export_neutralizes_formulas_escapes_html_and_redacts_credentials(): void
    {
        $this->actingAsAdmin();
        DB::table('audit_logs')->insert(['actor_label' => ' =1+1', 'action' => 'export_qa', 'new_values' => json_encode(['message' => '<script>alert(1)</script>', 'token' => 'SECRET', 'license_number' => 'PRIVATE']), 'created_at' => now()]);
        $q = 'category=audit&search=export_qa';
        $csv = $this->get('/api/admin/reports/export?'.$q.'&format=csv')->assertOk()->streamedContent();
        $this->assertStringContainsString("' =1+1", $csv);
        $this->assertStringNotContainsString('SECRET', $csv);
        $this->assertStringNotContainsString('PRIVATE', $csv);
        $html = $this->get('/api/admin/reports/export?'.$q.'&format=print')->assertOk()->streamedContent();
        $this->assertStringNotContainsString('<script>', $html);
        $this->assertStringContainsString('&lt;script&gt;', $html);
    }

    public function test_new_logins_logouts_account_decisions_and_settings_changes_are_audited(): void
    {
        $admin = $this->actingAsAdmin();
        DB::table('user_roles')->insert(['user_id' => $admin->user_id, 'role_id' => DB::table('roles')->where('role_code', 'admin')->value('role_id'), 'assigned_at' => now()]);
        $pending = $this->user('student', ['account_status' => 'pending']);
        $this->patchJson('/api/admin/users/'.$pending->user_id.'/approve')->assertOk();
        $this->assertDatabaseHas('audit_logs', ['action' => 'account_approved', 'auditable_id' => $pending->user_id]);
        $this->putJson('/api/admin/system-settings', ['system_name' => 'PASS QA', 'institution_name' => 'DYCI', 'contact_email' => 'qa@example.test', 'timezone' => 'Asia/Manila', 'date_format' => 'MM/DD/YYYY'])->assertOk();
        $this->assertDatabaseHas('audit_logs', ['action' => 'settings_updated']);
        $login = $this->postJson('/api/login', ['identifier' => $admin->email, 'password' => 'password'])->assertOk();
        $this->assertDatabaseHas('audit_logs', ['action' => 'login', 'user_id' => $admin->user_id]);
        // Use a real token for logout, rather than Sanctum's transient test token.
        $this->app['auth']->forgetGuards();
        $this->withToken($login->json('token'))->postJson('/api/logout')->assertOk();
        $this->assertDatabaseHas('audit_logs', ['action' => 'logout', 'user_id' => $admin->user_id]);
    }
}
