<?php

namespace App\Services\Reports;

use Carbon\CarbonImmutable;

final class ReportExport
{
    private static function value(mixed $value, string $key = ''): string
    {
        if ($value === null) {
            return '';
        }
        if (is_array($value)) {
            return json_encode($value, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
        }
        if (in_array($key, ['occurred_at', 'entry_at', 'exit_at'], true)) {
            return CarbonImmutable::parse($value)->setTimezone('Asia/Manila')->format('Y-m-d H:i:s P');
        }

        return (string) $value;
    }

    private static function csvCell(mixed $value): string
    {
        $s = (string) $value;

        // Neutralize spreadsheet formulas, including leading whitespace/control characters.
        return preg_match('/^[\s\x00-\x1f]*[=+@\-]/u', $s) ? "'".$s : $s;
    }

    public static function download(string $format, array $meta, array $summary, callable $rows)
    {
        $extension = match ($format) {
            'excel' => 'xml','print' => 'html',default => 'csv'
        };
        $type = match ($format) {
            'excel' => 'application/vnd.ms-excel; charset=UTF-8','print' => 'text/html; charset=UTF-8',default => 'text/csv; charset=UTF-8'
        };
        $filename = 'PASS-'.$meta['category'].'-'.$meta['filters']['date_from'].'-to-'.$meta['filters']['date_to'].'.'.$extension;

        return response()->streamDownload(function () use ($format, $meta, $summary, $rows) {
            $metadata = [
                ['Report', $meta['title']], ['Period (Manila)', $meta['filters']['date_from'].' to '.$meta['filters']['date_to']],
                ['Generated at', $meta['generated_at']], ['Generated by', $meta['generated_by']], ['Matching rows', $meta['total_records']],
                ['Filters', json_encode($meta['filters'], JSON_UNESCAPED_UNICODE)], ['Date basis', $meta['date_basis']],
            ];
            foreach ($summary as $m) {
                $metadata[] = [$m['label'], (string) $m['value'].(isset($m['unit']) ? ' '.$m['unit'] : '')];
            }
            $columns = $meta['columns'];
            if ($format === 'csv') {
                $out = fopen('php://output', 'w');
                fwrite($out, "\xEF\xBB\xBF");
                foreach ($metadata as $line) {
                    fputcsv($out, array_map(self::csvCell(...), $line), ',', '"', '');
                }
                fputcsv($out, [], ',', '"', '');
                fputcsv($out, array_values($columns), ',', '"', '');
                foreach ($rows() as $row) {
                    $row = (array) $row;
                    $cells = [];
                    foreach ($columns as $key => $label) {
                        $cells[] = self::csvCell(self::value($row[$key] ?? null, $key));
                    }fputcsv($out, $cells, ',', '"', '');
                }
                fclose($out);

                return;
            }
            $escape = fn ($v) => htmlspecialchars(preg_replace('/[\x00-\x08\x0B\x0C\x0E-\x1F]/u', '', (string) $v) ?? '', ENT_QUOTES | ENT_SUBSTITUTE | ENT_XML1, 'UTF-8');
            if ($format === 'excel') {
                // Excel 2003 XML is a real spreadsheet; all cells are literal strings, never executable formulas.
                echo '<?xml version="1.0" encoding="UTF-8"?><?mso-application progid="Excel.Sheet"?>';
                echo '<Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet" xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet"><Worksheet ss:Name="PASS report"><Table>';
                $write = function ($cells) use ($escape) {
                    echo '<Row>';
                    foreach ($cells as $cell) {
                        echo '<Cell><Data ss:Type="String">'.$escape($cell).'</Data></Cell>';
                    }echo '</Row>';
                };
                foreach ($metadata as $line) {
                    $write($line);
                }$write(array_values($columns));
                foreach ($rows() as $row) {
                    $row = (array) $row;
                    $cells = [];
                    foreach ($columns as $key => $label) {
                        $cells[] = self::value($row[$key] ?? null, $key);
                    }$write($cells);
                }
                echo '</Table></Worksheet></Workbook>';

                return;
            }
            echo '<!doctype html><html lang="en"><head><meta charset="utf-8"><title>'.$escape($meta['title']).'</title><style>@page{size:A4 landscape;margin:12mm}body{font:11px Arial,sans-serif;color:#17243a}h1{color:#080677;font-size:20px}table{width:100%;border-collapse:collapse}th,td{padding:6px;border:1px solid #dce1e8;text-align:left;overflow-wrap:anywhere;vertical-align:top}th{background:#eef1fa}thead{display:table-header-group}tr{break-inside:avoid}.meta{margin:3px 0}p{line-height:1.5}</style></head><body><h1>DYCI · PASS</h1>';
            foreach ($metadata as [$key,$value]) {
                echo '<p class="meta"><strong>'.$escape($key).': </strong>'.$escape($value).'</p>';
            }
            echo '<p>Print this report or choose Save as PDF in your browser. All matching rows are included; date/time values use Manila time.</p><table><thead><tr>';
            foreach ($columns as $label) {
                echo '<th>'.$escape($label).'</th>';
            }
            echo '</tr></thead><tbody>';
            foreach ($rows() as $row) {
                $row = (array) $row;
                echo '<tr>';
                foreach ($columns as $key => $label) {
                    echo '<td>'.$escape(self::value($row[$key] ?? null, $key)).'</td>';
                }echo '</tr>';
            }
            echo '</tbody></table><p>'.$escape($meta['date_basis']).'</p></body></html>';
        }, $filename, ['Content-Type' => $type, 'Cache-Control' => 'private, no-store', 'X-Content-Type-Options' => 'nosniff', 'Content-Security-Policy' => "default-src 'none'; style-src 'unsafe-inline'"]);
    }
}
